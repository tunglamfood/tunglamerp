-- Daily production planning: orders for a delivery date → what each line makes,
-- in full batches, with tonight's prep (soaking) and raw materials, then the actual
-- output, lot numbers and expiry dates for traceability.

-- Who can open it: a new staff area.
alter table erp_users drop constraint if exists erp_users_areas_ck;
alter table erp_users add constraint erp_users_areas_ck check (areas <@ array['hr', 'sales', 'website', 'admin', 'production']::text[]);

-- Production lines / stations, in the order the factory runs them.
create table if not exists prod_lines (
  code       text primary key,
  name       text not null,
  sort       integer not null default 0,
  active     boolean not null default true
);

-- How each sellable item is supplied:
--   make — produced here: counts towards `makes_item` × `units_per` (a carton of 180 tubes
--          makes 180 of the tube; a 3-pack makes 3);
--   buy  — bought-in / trading goods: listed for picking, not produced;
--   none — not a product (services, rent, raw materials sold off).
-- A "base" product is one that `makes` itself: it carries the line, batch and recipe.
create table if not exists prod_items (
  item_code       text primary key references sales_products(item_code) on delete cascade,
  mode            text not null default 'make',
  makes_item      text references sales_products(item_code) on delete set null,
  units_per       numeric(12, 3) not null default 1,
  line_code       text references prod_lines(code) on delete set null,
  batch_size      numeric(12, 2),          -- units per batch / mould / tray; empty = no rounding
  min_run         numeric(12, 2),          -- never make fewer than this when there is any demand
  buffer_pct      numeric(5, 2) not null default 0,  -- extra for walk-ins, van stock, breakage
  shelf_life_days integer,                 -- for expiry dates on lots
  recipe_yield    numeric(12, 2),          -- units one recipe makes (usually the batch size)
  sort            integer not null default 0,
  updated_at      timestamptz not null default now(),
  constraint prod_items_mode_ck check (mode in ('make', 'buy', 'none')),
  constraint prod_items_units_ck check (units_per > 0),
  constraint prod_items_buffer_ck check (buffer_pct >= 0 and buffer_pct <= 200)
);

-- What one recipe (recipe_yield units) of a base product takes. `prep_before`: done
-- before production starts (soaking soybeans), so it is listed first, for the night before.
create table if not exists prod_recipe_lines (
  id           bigint generated by default as identity primary key,
  item_code    text not null references prod_items(item_code) on delete cascade,
  ingredient   text not null references sales_products(item_code) on delete restrict,
  qty          numeric(12, 4) not null check (qty > 0),
  uom          text not null default '',
  prep_before  boolean not null default false,
  note         text,
  sort         integer not null default 0
);
create index if not exists prod_recipe_lines_item_idx on prod_recipe_lines (item_code, sort);

-- One plan per delivery date. Locking keeps the quantities the factory works to;
-- orders arriving afterwards show up as a difference instead of silently changing it.
create table if not exists prod_plans (
  id             bigint generated by default as identity primary key,
  delivery_date  date not null unique,
  status         text not null default 'draft',
  locked_at      timestamptz,
  locked_by      text,
  note           text,
  updated_at     timestamptz not null default now(),
  constraint prod_plans_status_ck check (status in ('draft', 'locked', 'done'))
);

create table if not exists prod_plan_lines (
  id           bigint generated by default as identity primary key,
  plan_id      bigint not null references prod_plans(id) on delete cascade,
  item_code    text not null references sales_products(item_code) on delete cascade,
  ordered_qty  numeric(12, 2) not null default 0,   -- from orders when locked
  stock_qty    numeric(12, 2) not null default 0,   -- usable stock carried over, taken off
  extra_qty    numeric(12, 2) not null default 0,   -- a manual top-up on the day
  plan_qty     numeric(12, 2) not null default 0,   -- what was decided to make
  batches      numeric(12, 2),
  actual_qty   numeric(12, 2),                      -- what was really made
  waste_qty    numeric(12, 2),
  lot_no       text,
  produced_on  date,
  expiry_date  date,
  note         text,
  constraint prod_plan_lines_unique unique (plan_id, item_code)
);

alter table prod_lines        enable row level security;
alter table prod_items        enable row level security;
alter table prod_recipe_lines enable row level security;
alter table prod_plans        enable row level security;
alter table prod_plan_lines   enable row level security;

