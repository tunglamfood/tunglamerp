-- ─────────────────────────────────────────────────────────────────────────────
-- Dealer portal foundations (tunglamfood.my/portal ↔ this ERP)
--
-- Additive only: new tables, new nullable/defaulted columns, new functions.
-- Nothing existing is renamed or dropped, so the running ERP keeps working.
--
-- The portal never keeps its own copy of trading data. It reads and writes
-- these tables from its server, and the rules that decide money — which price
-- applies, what the next order number is, what an order totals — live here as
-- functions, so the portal and the ERP can never disagree.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1. Which currency a dealer is invoiced in (Singapore dealers may become SGD).
alter table sales_customers
  add column if not exists currency text not null default 'MYR';
do $$ begin
  alter table sales_customers add constraint sales_customers_currency_ck check (currency in ('MYR', 'SGD'));
exception when duplicate_object then null; end $$;

-- 2. The portal catalogue. Item codes stay exactly as they are (and as the
--    accounting system knows them); the portal shows several codes as one
--    product with variants — "Taufu Keras: 2 pcs · 4 pcs · 10 pcs".
create table if not exists portal_products (
  id            bigint generated by default as identity primary key,
  name_en       text not null,
  name_ms       text,
  name_zh       text,
  category      text not null default 'tofu',   -- tofu | steamboat | dessert | grocery
  brand         text not null default '',
  website_slug  text,                            -- photo + description from tunglamfood.my
  -- Private-label products (a customer's own brand) are only shown to dealers
  -- who have their own or their group's price for one of its variants.
  restricted    boolean not null default false,
  sort          integer not null default 0,
  active        boolean not null default true,
  updated_at    timestamptz not null default now()
);

create table if not exists portal_product_variants (
  item_code     text primary key references sales_products(item_code) on delete cascade,
  product_id    bigint not null references portal_products(id) on delete cascade,
  label_en      text not null,
  label_ms      text,
  label_zh      text,
  website_slug  text,                            -- optional photo of this exact pack
  sort          integer not null default 0,
  active        boolean not null default true
);
create index if not exists portal_product_variants_product_idx on portal_product_variants (product_id, sort);

-- 3. Sales reps and the dealers each one looks after.
create table if not exists sales_reps (
  code        text primary key,
  name        text not null,
  phone       text,
  worker_code text,                               -- optional link to hr_workers.code
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

create table if not exists sales_rep_customers (
  rep_code      text not null references sales_reps(code) on delete cascade,
  customer_code text not null references sales_customers(code) on delete cascade,
  primary key (rep_code, customer_code)
);
create index if not exists sales_rep_customers_customer_idx on sales_rep_customers (customer_code);

-- 4. Who may sign in to the portal. One row per phone number: a dealer can
--    have several (owner, purchaser), a chain group logs in for all its
--    outlets, a rep orders for the dealers assigned to them.
create table if not exists portal_accounts (
  id            bigint generated by default as identity primary key,
  phone         text not null unique,
  name          text not null default '',
  role          text not null,
  customer_code text references sales_customers(code) on delete cascade,
  group_code    text references sales_groups(code) on delete cascade,
  rep_code      text references sales_reps(code) on delete cascade,
  active        boolean not null default true,
  last_login_at timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint portal_accounts_phone_ck check (phone ~ '^\+[1-9][0-9]{7,14}$'),
  constraint portal_accounts_role_ck check (role in ('dealer', 'rep')),
  constraint portal_accounts_owner_ck check (
    (role = 'dealer' and rep_code is null and ((customer_code is not null) <> (group_code is not null)))
    or (role = 'rep' and rep_code is not null and customer_code is null and group_code is null)
  )
);

-- Sign-in attempts: rate limits and an audit trail.
create table if not exists portal_auth_events (
  id     bigint generated by default as identity primary key,
  phone  text not null,
  ip     text,
  kind   text not null check (kind in ('send', 'ok', 'fail', 'blocked')),
  at     timestamptz not null default now()
);
create index if not exists portal_auth_events_phone_idx on portal_auth_events (phone, at desc);
create index if not exists portal_auth_events_ip_idx on portal_auth_events (ip, at desc);

-- 5. Orders: where each one came from and who placed it.
alter table sales_orders add column if not exists source            text not null default 'erp';
alter table sales_orders add column if not exists placed_by         text;
alter table sales_orders add column if not exists portal_account_id bigint references portal_accounts(id) on delete set null;
alter table sales_orders add column if not exists submitted_at      timestamptz;
alter table sales_orders add column if not exists currency          text not null default 'MYR';
do $$ begin
  alter table sales_orders add constraint sales_orders_source_ck check (source in ('erp', 'portal', 'rep'));
exception when duplicate_object then null; end $$;
create index if not exists sales_orders_status_idx on sales_orders (status, order_date desc);

-- Which rule priced a line when it was ordered: dealer | group | list | none.
alter table sales_order_lines add column if not exists price_source text;

-- Every change to an order, for both sides to see.
create table if not exists sales_order_events (
  id        bigint generated by default as identity primary key,
  order_id  bigint not null references sales_orders(id) on delete cascade,
  at        timestamptz not null default now(),
  actor     text not null,
  kind      text not null,
  detail    jsonb
);
create index if not exists sales_order_events_order_idx on sales_order_events (order_id, at);

-- Row level security on, no public policy — like every other table here:
-- only the two servers (ERP, portal) reach the data, with the secret key.
alter table portal_products          enable row level security;
alter table portal_product_variants  enable row level security;
alter table sales_reps               enable row level security;
alter table sales_rep_customers      enable row level security;
alter table portal_accounts          enable row level security;
alter table portal_auth_events       enable row level security;
alter table sales_order_events       enable row level security;

