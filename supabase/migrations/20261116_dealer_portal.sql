-- Functions
-- ─────────────────────────────────────────────────────────────────────────────

-- Today in Malaysia (the database clock runs in UTC).
create or replace function sales_today() returns date
language sql stable as $$ select (now() at time zone 'Asia/Kuala_Lumpur')::date $$;

-- The price one dealer pays for one item on a day:
-- the dealer's own price → their group's price → the item's list price.
create or replace function sales_price_for(p_customer text, p_item text, p_on date default null)
returns table (price numeric, source text, effective_from date)
language sql stable as $$
  with d as (select coalesce(p_on, sales_today()) as on_date),
  c as (select group_code from sales_customers where code = p_customer),
  candidates as (
    (select sp.price, 'dealer'::text as source, sp.effective_from, 1 as rank
       from sales_prices sp, d
      where sp.customer_code = p_customer and sp.item_code = p_item and sp.effective_from <= d.on_date
      order by sp.effective_from desc limit 1)
    union all
    (select sp.price, 'group', sp.effective_from, 2
       from sales_prices sp, c, d
      where c.group_code is not null and sp.group_code = c.group_code
        and sp.item_code = p_item and sp.effective_from <= d.on_date
      order by sp.effective_from desc limit 1)
    union all
    (select p.base_price, 'list', null::date, 3
       from sales_products p where p.item_code = p_item and p.base_price > 0)
  )
  select price, source, effective_from from candidates order by rank limit 1
$$;

-- The next order number, SO-YYYY-MM-NNNN, safe when two people save at once.
-- The lock is held until the calling transaction ends, so call it inside the
-- same transaction that inserts the order (portal_place_order does).
create or replace function sales_next_order_no(p_on date default null)
returns text language plpgsql as $$
declare
  d      date := coalesce(p_on, sales_today());
  prefix text := 'SO-' || to_char(d, 'YYYY-MM') || '-';
  n      integer;
begin
  perform pg_advisory_xact_lock(hashtext('sales_order_no'));
  select coalesce(max(substring(order_no from length(prefix) + 1)::integer), 0) into n
    from sales_orders
   where order_no like prefix || '%'
     and substring(order_no from length(prefix) + 1) ~ '^[0-9]+$';
  return prefix || lpad((n + 1)::text, 4, '0');
end $$;

-- The dealers (customer codes) one portal account may order for.
create or replace function portal_allowed_customers(p_account bigint)
returns setof text language sql stable as $$
  select c.code
    from portal_accounts a
    join sales_customers c on c.active and (
         (a.role = 'dealer' and a.customer_code = c.code)
      or (a.role = 'dealer' and a.group_code is not null and c.group_code = a.group_code)
      or (a.role = 'rep' and exists (
            select 1 from sales_rep_customers rc where rc.rep_code = a.rep_code and rc.customer_code = c.code)))
   where a.id = p_account and a.active
$$;

-- Everything one dealer can order, with their price for each variant.
create or replace function portal_catalog(p_customer text, p_on date default null)
returns table (
  product_id bigint, name_en text, name_ms text, name_zh text, category text, brand text,
  website_slug text, product_sort integer,
  item_code text, description text, uom text,
  label_en text, label_ms text, label_zh text, variant_slug text, variant_sort integer,
  price numeric, price_source text
)
language sql stable as $$
  with priced as (
    select p.id as product_id, p.name_en, p.name_ms, p.name_zh, p.category, p.brand,
           p.website_slug, p.sort as product_sort, p.restricted,
           v.item_code, sp.description, sp.uom,
           v.label_en, v.label_ms, v.label_zh, v.website_slug as variant_slug, v.sort as variant_sort,
           pr.price, coalesce(pr.source, 'none') as price_source
      from portal_products p
      join portal_product_variants v on v.product_id = p.id and v.active
      join sales_products sp on sp.item_code = v.item_code and sp.active
      left join lateral sales_price_for(p_customer, v.item_code, p_on) pr on true
     where p.active
  )
  select product_id, name_en, name_ms, name_zh, category, brand, website_slug, product_sort,
         item_code, description, uom, label_en, label_ms, label_zh, variant_slug, variant_sort,
         price, price_source
    from priced x
   where not x.restricted
      or exists (select 1 from priced y
                  where y.product_id = x.product_id and y.price_source in ('dealer', 'group'))
   order by product_sort, name_en, variant_sort, item_code
$$;

-- Places an order from the portal. Prices and totals are worked out here,
-- never taken from the browser. Returns the new order number.
-- p_lines: [{"item_code": "TK4P", "qty": 10}, …]
create or replace function portal_place_order(
  p_account   bigint,
  p_customer  text,
  p_lines     jsonb,
  p_deliver_on date default null,
  p_their_ref text default null,
  p_note      text default null
) returns text
language plpgsql security definer set search_path = public as $$
declare
  acc      portal_accounts%rowtype;
  cust     sales_customers%rowtype;
  today    date := sales_today();
  v_no     text;
  v_id     bigint;
  v_line   integer := 0;
  r        record;
  pr       record;
begin
  select * into acc from portal_accounts where id = p_account and active;
  if not found then raise exception 'portal:account_inactive'; end if;

  if not exists (select 1 from portal_allowed_customers(p_account) x where x = p_customer) then
    raise exception 'portal:not_allowed';
  end if;
  select * into cust from sales_customers where code = p_customer;

  if p_lines is null or jsonb_typeof(p_lines) <> 'array'
     or jsonb_array_length(p_lines) = 0 or jsonb_array_length(p_lines) > 200 then
    raise exception 'portal:no_lines';
  end if;
  if p_deliver_on is not null and (p_deliver_on < today or p_deliver_on > today + 60) then
    raise exception 'portal:bad_delivery_date';
  end if;

  v_no := sales_next_order_no(today);
  insert into sales_orders (order_no, customer_code, order_date, deliver_on, status, their_ref, note,
                            source, placed_by, portal_account_id, submitted_at, currency)
  values (v_no, p_customer, today, p_deliver_on, 'submitted',
          nullif(left(btrim(coalesce(p_their_ref, '')), 60), ''),
          nullif(left(btrim(coalesce(p_note, '')), 1000), ''),
          case when acc.role = 'rep' then 'rep' else 'portal' end,
          coalesce(nullif(acc.name, ''), acc.phone), acc.id, now(), cust.currency)
  returning id into v_id;

  -- Same item twice in the basket becomes one line; keep the basket's order.
  for r in
    select upper(btrim(t.e->>'item_code')) as item_code,
           sum(case when (t.e->>'qty') ~ '^[0-9]+$' then (t.e->>'qty')::numeric else null end) as qty,
           bool_or((t.e->>'qty') !~ '^[0-9]+$') as bad_qty,
           min(t.n) as first_seen
      from jsonb_array_elements(p_lines) with ordinality as t(e, n)
     group by 1
     order by first_seen
  loop
    if r.bad_qty or r.qty is null or r.qty <= 0 or r.qty > 100000 then
      raise exception 'portal:bad_qty:%', r.item_code;
    end if;
    -- Only items this dealer can actually see in their catalogue.
    if not exists (select 1 from portal_catalog(p_customer, today) c where c.item_code = r.item_code) then
      raise exception 'portal:item_unavailable:%', r.item_code;
    end if;

    select * into pr from sales_price_for(p_customer, r.item_code, today);
    v_line := v_line + 1;
    insert into sales_order_lines (order_id, line_no, item_code, qty, uom, price, price_source)
    select v_id, v_line, r.item_code, r.qty, sp.uom, coalesce(pr.price, 0), coalesce(pr.source, 'none')
      from sales_products sp where sp.item_code = r.item_code;
  end loop;

  insert into sales_order_events (order_id, actor, kind, detail)
  values (v_id, coalesce(nullif(acc.name, ''), acc.phone), 'submitted',
          jsonb_build_object('lines', v_line, 'via', case when acc.role = 'rep' then 'rep' else 'portal' end));

  return v_no;
end $$;

-- A dealer (or their rep) may cancel an order until the office confirms it.
create or replace function portal_cancel_order(p_account bigint, p_order_no text, p_reason text default null)
returns void
language plpgsql security definer set search_path = public as $$
declare
  acc portal_accounts%rowtype;
  o   sales_orders%rowtype;
begin
  select * into acc from portal_accounts where id = p_account and active;
  if not found then raise exception 'portal:account_inactive'; end if;
  select * into o from sales_orders where order_no = p_order_no for update;
  if not found or not exists (select 1 from portal_allowed_customers(p_account) x where x = o.customer_code) then
    raise exception 'portal:not_found';
  end if;
  if o.status <> 'submitted' then raise exception 'portal:already_confirmed'; end if;

  update sales_orders set status = 'cancelled', updated_at = now() where id = o.id;
  insert into sales_order_events (order_id, actor, kind, detail)
  values (o.id, coalesce(nullif(acc.name, ''), acc.phone), 'cancelled',
          jsonb_build_object('reason', nullif(left(btrim(coalesce(p_reason, '')), 300), '')));
end $$;

