-- Promotions: a promo price (or a % off the dealer's own price) for one item, for
-- all dealers, one group or one dealer, between two dates, optionally only from a
-- minimum quantity ("RM 1.80 each from 50 pcs"). The database decides the price at
-- order time — the portal only shows it.

create table if not exists sales_promotions (
  id            bigint generated by default as identity primary key,
  title_en      text not null,
  title_ms      text,
  title_zh      text,
  item_code     text not null references sales_products(item_code) on delete cascade,
  kind          text not null,
  value         numeric(12, 2) not null,
  min_qty       integer not null default 1,
  customer_code text references sales_customers(code) on delete cascade,
  group_code    text references sales_groups(code) on delete cascade,
  starts_on     date not null default sales_today(),
  ends_on       date,
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint sales_promotions_kind_ck check (kind in ('price', 'percent')),
  constraint sales_promotions_value_ck check (value > 0 and (kind <> 'percent' or value < 100)),
  constraint sales_promotions_min_qty_ck check (min_qty >= 1),
  constraint sales_promotions_target_ck check (not (customer_code is not null and group_code is not null)),
  constraint sales_promotions_dates_ck check (ends_on is null or ends_on >= starts_on)
);
create index if not exists sales_promotions_item_idx on sales_promotions (item_code) where active;
alter table sales_promotions enable row level security;  -- no policies: server keys only

-- The best promotion for one dealer and item on a day. With a quantity, only tiers
-- that quantity reaches count; without one (the catalogue), the best tier is shown.
create or replace function sales_promo_for(p_customer text, p_item text, p_qty numeric default null, p_on date default null)
returns table (promo_id bigint, price numeric, min_qty integer, title_en text, title_ms text, title_zh text, ends_on date)
language sql stable as $$
  with d as (select coalesce(p_on, sales_today()) as on_date),
  c as (select group_code from sales_customers where code = p_customer),
  base as (select price from sales_price_for(p_customer, p_item, p_on)),
  cand as (
    select pm.id, pm.min_qty, pm.title_en, pm.title_ms, pm.title_zh, pm.ends_on,
           case when pm.kind = 'price' then pm.value
                else round((select price from base) * (1 - pm.value / 100), 2) end as price
      from sales_promotions pm, d
     where pm.active and pm.item_code = p_item
       and pm.starts_on <= d.on_date and (pm.ends_on is null or pm.ends_on >= d.on_date)
       and (pm.customer_code is null or pm.customer_code = p_customer)
       and (pm.group_code is null or pm.group_code is not distinct from (select group_code from c))
       and (p_qty is null or pm.min_qty <= p_qty)
  )
  select id, price, min_qty, title_en, title_ms, title_zh, ends_on
    from cand
   where price is not null and price > 0
   order by price asc, min_qty asc
   limit 1
$$;

-- Every promotion a dealer can see today, with their normal price beside it.
create or replace function portal_promotions(p_customer text, p_on date default null)
returns table (item_code text, price numeric, min_qty integer, title_en text, title_ms text, title_zh text, ends_on date, normal_price numeric)
language sql stable as $$
  select v.item_code, pr.price, pr.min_qty, pr.title_en, pr.title_ms, pr.title_zh, pr.ends_on, np.price
    from (select distinct item_code from sales_promotions where active) v
    cross join lateral sales_promo_for(p_customer, v.item_code, null, p_on) pr
    left join lateral sales_price_for(p_customer, v.item_code, p_on) np on true
   where np.price is null or pr.price < np.price
$$;

-- Placing an order: unchanged, except that each line takes the promotion price when
-- its quantity qualifies and it is lower than the dealer's own price.
create or replace function portal_place_order(p_account bigint, p_customer text, p_lines jsonb, p_deliver_on date default null, p_their_ref text default null, p_note text default null)
returns text
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  acc      portal_accounts%rowtype;
  cust     sales_customers%rowtype;
  today    date := sales_today();
  v_no     text;
  v_id     bigint;
  v_line   integer := 0;
  v_status text;
  r        record;
  pr       record;
  pm       record;
  v_price  numeric;
  v_source text;
begin
  select * into acc from portal_accounts where id = p_account and active;
  if not found then raise exception 'portal:account_inactive'; end if;

  if not exists (select 1 from portal_allowed_customers(p_account) x where x = p_customer) then
    raise exception 'portal:not_allowed';
  end if;
  select * into cust from sales_customers where code = p_customer;
  v_status := case when cust.on_hold then 'on_hold' else 'submitted' end;

  if p_lines is null or jsonb_typeof(p_lines) <> 'array'
     or jsonb_array_length(p_lines) = 0 or jsonb_array_length(p_lines) > 200 then
    raise exception 'portal:no_lines';
  end if;
  if p_deliver_on is not null and (p_deliver_on < today or p_deliver_on > today + 60) then
    raise exception 'portal:bad_delivery_date';
  end if;

  v_no := sales_next_order_no(today);
  insert into sales_orders (order_no, customer_code, order_date, deliver_on, status, their_ref, note,
                            source, placed_by, portal_account_id, submitted_at, currency)
  values (v_no, p_customer, today, p_deliver_on, v_status,
          nullif(left(btrim(coalesce(p_their_ref, '')), 60), ''),
          nullif(left(btrim(coalesce(p_note, '')), 1000), ''),
          case when acc.role = 'rep' then 'rep' else 'portal' end,
          coalesce(nullif(acc.name, ''), acc.phone), acc.id, now(), cust.currency)
  returning id into v_id;

  for r in
    select upper(btrim(t.e->>'item_code')) as item_code,
           sum(case when (t.e->>'qty') ~ '^[0-9]+$' then (t.e->>'qty')::numeric else null end) as qty,
           bool_or((t.e->>'qty') !~ '^[0-9]+$') as bad_qty,
           min(t.n) as first_seen
      from jsonb_array_elements(p_lines) with ordinality as t(e, n)
     group by 1
     order by first_seen
  loop
    if r.bad_qty or r.qty is null or r.qty <= 0 or r.qty > 100000 then
      raise exception 'portal:bad_qty:%', r.item_code;
    end if;
    if not exists (select 1 from portal_catalog(p_customer, today) c where c.item_code = r.item_code) then
      raise exception 'portal:item_unavailable:%', r.item_code;
    end if;

    select * into pr from sales_price_for(p_customer, r.item_code, today);
    select * into pm from sales_promo_for(p_customer, r.item_code, r.qty, today);
    if pm.price is not null and (pr.price is null or pm.price < pr.price) then
      v_price := pm.price; v_source := 'promo';
    else
      v_price := coalesce(pr.price, 0); v_source := coalesce(pr.source, 'none');
    end if;
    v_line := v_line + 1;
    insert into sales_order_lines (order_id, line_no, item_code, qty, uom, price, price_source)
    select v_id, v_line, r.item_code, r.qty, sp.uom, v_price, v_source
      from sales_products sp where sp.item_code = r.item_code;
  end loop;

  insert into sales_order_events (order_id, actor, kind, detail)
  values (v_id, coalesce(nullif(acc.name, ''), acc.phone), 'submitted',
          jsonb_build_object('lines', v_line, 'via', case when acc.role = 'rep' then 'rep' else 'portal' end));
  if v_status = 'on_hold' then
    insert into sales_order_events (order_id, actor, kind, detail)
    values (v_id, 'System', 'on_hold', jsonb_build_object('reason', cust.hold_reason));
  end if;

  return v_no;
end $function$;
