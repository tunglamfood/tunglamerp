-- ─────────────────────────────────────────────────────────────────────────────
-- Dealer portal, phases 2–4: credit terms & on-hold, AutoCount export marks,
-- dealer announcements, "usual items", and real one-time codes.
-- Additive only.
-- ─────────────────────────────────────────────────────────────────────────────

-- 1. Credit terms per dealer. A dealer on hold can still order on the portal,
--    but their orders arrive as "on_hold" for the office to review.
alter table sales_customers add column if not exists payment_terms text not null default '';
alter table sales_customers add column if not exists credit_limit  numeric;
alter table sales_customers add column if not exists on_hold       boolean not null default false;
alter table sales_customers add column if not exists hold_reason   text;

-- 2. When an order went to the accounting system (AutoCount), so it is never exported twice.
alter table sales_orders add column if not exists exported_at timestamptz;
alter table sales_orders add column if not exists export_ref  text;
create index if not exists sales_orders_export_idx on sales_orders (exported_at, status, order_date);

-- 3. Notices the office shows on the portal's home page.
create table if not exists portal_announcements (
  id         bigint generated by default as identity primary key,
  title_en   text not null,
  title_ms   text,
  title_zh   text,
  body_en    text not null default '',
  body_ms    text,
  body_zh    text,
  starts_on  date,
  ends_on    date,
  active     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table portal_announcements enable row level security;

-- 4. One-time sign-in codes (real SMS). Only a hash is kept; 5 minutes, 5 tries.
create table if not exists portal_otp (
  phone      text primary key,
  code_hash  text not null,
  expires_at timestamptz not null,
  attempts   integer not null default 0,
  created_at timestamptz not null default now()
);
alter table portal_otp enable row level security;

