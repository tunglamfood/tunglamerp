-- Payment slips dealers upload on the portal (bank transfer receipts), checked by
-- the office in Sales → Payments. The amount is what the dealer typed; nothing here
-- calculates money. Files live in the private "payment-slips" bucket, reached only
-- by the two servers with their secret keys.
create table if not exists portal_payments (
  id                bigint generated by default as identity primary key,
  customer_code     text not null references sales_customers(code) on delete cascade,
  portal_account_id bigint references portal_accounts(id) on delete set null,
  placed_by         text,
  order_no          text,
  amount            numeric(12, 2) not null check (amount > 0),
  currency          text not null default 'MYR',
  paid_on           date not null,
  reference         text,
  note              text,
  file_path         text not null,
  file_type         text not null,
  status            text not null default 'submitted',
  office_note       text,
  checked_by        text,
  checked_at        timestamptz,
  created_at        timestamptz not null default now(),
  constraint portal_payments_status_ck check (status in ('submitted', 'checked', 'rejected'))
);
create index if not exists portal_payments_customer_idx on portal_payments (customer_code, created_at desc);
create index if not exists portal_payments_status_idx on portal_payments (status, created_at desc);
alter table portal_payments enable row level security;  -- no policies: server keys only

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('payment-slips', 'payment-slips', false, 4194304,
        array['image/jpeg', 'image/png', 'image/webp', 'application/pdf'])
on conflict (id) do nothing;
