-- Outstanding invoices and stock, imported from AutoCount exports (Excel/CSV) in
-- ERP → Sales → Accounts & stock. Each import replaces the previous snapshot.
create table if not exists ar_invoices (
  id            bigint generated by default as identity primary key,
  customer_code text not null references sales_customers(code) on delete cascade,
  doc_no        text not null,
  doc_type      text not null default 'IV',
  doc_date      date not null,
  due_date      date,
  amount        numeric(14, 2) not null,
  outstanding   numeric(14, 2) not null,
  ref           text,
  constraint ar_invoices_doc_unique unique (customer_code, doc_no)
);
create index if not exists ar_invoices_customer_idx on ar_invoices (customer_code, doc_date);
alter table ar_invoices enable row level security;

create table if not exists stock_levels (
  item_code text primary key references sales_products(item_code) on delete cascade,
  qty       numeric(14, 2) not null,
  uom       text
);
alter table stock_levels enable row level security;

create table if not exists data_imports (
  id        bigint generated by default as identity primary key,
  kind      text not null check (kind in ('ar', 'stock')),
  file_name text,
  rows      integer not null,
  skipped   integer not null default 0,
  as_of     date not null,
  by_name   text,
  at        timestamptz not null default now()
);
alter table data_imports enable row level security;

-- One dealer's statement: every open document with days overdue, and the totals.
create or replace function portal_statement(p_customer text)
returns table (doc_no text, doc_type text, doc_date date, due_date date, amount numeric, outstanding numeric,
               days_overdue integer, total_outstanding numeric, total_overdue numeric, as_of date)
language sql stable as $$
  with t as (select sales_today() as today),
  inv as (
    select i.*, greatest(0, (select today from t) - coalesce(i.due_date, i.doc_date))::int as od
      from ar_invoices i where i.customer_code = p_customer and i.outstanding <> 0
  )
  select inv.doc_no, inv.doc_type, inv.doc_date, inv.due_date, inv.amount, inv.outstanding, inv.od,
         sum(inv.outstanding) over (),
         sum(case when inv.od > 0 then inv.outstanding else 0 end) over (),
         (select max(as_of) from data_imports where kind = 'ar')
    from inv
   order by inv.doc_date, inv.doc_no
$$;
