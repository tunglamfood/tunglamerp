-- Personal staff logins, and website enquiries as sales leads.
--
-- Additive only: nothing existing is changed or removed.

-- 1. Staff logins. One row per person. `areas` says what they can open:
--      hr      — workers, monthly pay, payslips, holidays
--      sales   — orders, customers, products, prices, dealer portal, enquiries
--      website — the content admin at tunglamfood.my/admin
--      admin   — staff logins (this table)
--    Passwords are stored only as scrypt hashes. `session_version` is bumped to
--    sign someone out everywhere (password reset, access changed, switched off).
create table if not exists erp_users (
  id                   bigint generated by default as identity primary key,
  username             text not null unique,
  name                 text not null,
  areas                text[] not null default '{}',
  password_hash        text not null,
  must_change_password boolean not null default true,
  active               boolean not null default true,
  session_version      integer not null default 1,
  failed_count         integer not null default 0,
  locked_until         timestamptz,
  last_login_at        timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint erp_users_username_ck check (username ~ '^[a-z0-9._-]{2,40}$'),
  constraint erp_users_name_ck check (char_length(name) between 1 and 80),
  constraint erp_users_areas_ck check (areas <@ array['hr', 'sales', 'website', 'admin']::text[])
);
alter table erp_users enable row level security;  -- no policies: server keys only

-- 2. Each person's assistant conversations are their own.
alter table assistant_sessions add column if not exists user_id bigint references erp_users(id) on delete set null;
create index if not exists assistant_sessions_user_idx on assistant_sessions (user_id, updated_at desc);

-- 3. Enquiries from tunglamfood.my, followed up by the sales office.
create table if not exists sales_leads (
  id            bigint generated by default as identity primary key,
  source        text not null default 'website',
  website_id    uuid unique,            -- inquiries.id on the website, so a resend never duplicates
  kind          text not null default 'general',
  name          text not null,
  company       text,
  email         text,
  phone         text,
  message       text,
  product_slug  text,
  locale        text,
  page_url      text,
  status        text not null default 'new',
  note          text,
  customer_code text references sales_customers(code) on delete set null,
  handled_by    text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint sales_leads_kind_ck check (kind in ('general', 'wholesale', 'product')),
  constraint sales_leads_status_ck check (status in ('new', 'contacted', 'won', 'lost', 'spam')),
  constraint sales_leads_name_ck check (char_length(name) between 1 and 120)
);
create index if not exists sales_leads_status_idx on sales_leads (status, created_at desc);
create index if not exists sales_leads_customer_idx on sales_leads (customer_code);
alter table sales_leads enable row level security;  -- no policies: server keys only
