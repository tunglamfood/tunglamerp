-- Sales rep visits, recorded on the dealer portal: check in at a dealer (with the
-- phone's location if the rep allows it), add photos and a note, check out. The
-- office sees them in ERP → Sales → Visits. Photos live in the private
-- "visit-photos" bucket, reached only by the two servers.
create table if not exists sales_visits (
  id                bigint generated by default as identity primary key,
  rep_code          text not null references sales_reps(code) on delete cascade,
  portal_account_id bigint references portal_accounts(id) on delete set null,
  customer_code     text not null references sales_customers(code) on delete cascade,
  checked_in_at     timestamptz not null default now(),
  checked_out_at    timestamptz,
  in_lat            double precision,
  in_lng            double precision,
  in_accuracy_m     integer,
  out_lat           double precision,
  out_lng           double precision,
  outcome           text,
  note              text,
  photo_paths       text[] not null default '{}',
  constraint sales_visits_outcome_ck check (outcome is null or outcome in ('ordered', 'no_order', 'collected', 'follow_up', 'closed'))
);
create index if not exists sales_visits_rep_idx on sales_visits (rep_code, checked_in_at desc);
create index if not exists sales_visits_customer_idx on sales_visits (customer_code, checked_in_at desc);
-- At most one open visit per rep.
create unique index if not exists sales_visits_one_open on sales_visits (rep_code) where checked_out_at is null;
alter table sales_visits enable row level security;  -- no policies: server keys only

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('visit-photos', 'visit-photos', false, 4194304, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;
